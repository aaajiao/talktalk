#!/bin/bash
# gen-expected-duration.sh [--check]: generate Sources/TalkTalkCore/Generated/ExpectedDurationTable.swift
# from engine/talktalk_engine/expected_duration.json, the one data file the engine's
# expected_seconds (tts.py) also reads (§5.5). --check exits 1 when the committed file is out of date.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
# shellcheck source=lib/common.sh
. "$here/lib/common.sh"
root="$(cd "$here/.." && pwd)"
src="$root/engine/talktalk_engine/expected_duration.json"
out="$root/Sources/TalkTalkCore/Generated/ExpectedDurationTable.swift"

gen() {
  "${TALKTALK_DEV_PYTHON:-/usr/bin/python3}" -I -B - "$src" <<'EOF'
import json, sys
d = json.load(open(sys.argv[1], encoding="utf-8"))
if d.get("version") != 1:
    sys.exit("expected_duration.json: unsupported version %r" % d.get("version"))
langs = d["languages"]
default = d["default"]
if default not in langs:
    sys.exit("expected_duration.json: default %r is not in languages" % default)
print("// Generated by scripts/gen-expected-duration.sh from engine/talktalk_engine/expected_duration.json.")
print("// Do not edit. check.sh fails when this file and the JSON disagree.")
print("")
print("enum ExpectedDurationTable {")
print("    static let source = %s" % json.dumps(d.get("source", ""), ensure_ascii=False))
print("    /// Languages not listed use this one (tts.py: `_EXPECTED.get(lang, _EXPECTED[default])`).")
print("    static let defaultLanguage = %s" % json.dumps(default))
print("    /// language code -> (intercept_s, per_word_s)")
print("    static let languages: [String: (interceptS: Double, perWordS: Double)] = [")
for k in sorted(langs):
    v = langs[k]
    print("        %s: (interceptS: %r, perWordS: %r)," % (json.dumps(k), float(v["intercept_s"]), float(v["per_word_s"])))
print("    ]")
print("}")
EOF
}

if [ "${1:-}" = "--check" ]; then
  if gen | /usr/bin/cmp -s - "$out"; then tt_log "ExpectedDurationTable.swift: in sync"; exit 0; fi
  tt_log "ExpectedDurationTable.swift is out of date; run scripts/gen-expected-duration.sh"; exit 1
fi
/bin/mkdir -p "$(/usr/bin/dirname "$out")"
gen > "$out"
