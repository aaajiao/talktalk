#!/bin/bash
# gen-pins.sh [--check]: generate Sources/TalkTalkCore/Generated/EnginePins.swift,
# Sources/TalkTalkCore/Generated/DriverPins.swift, Driver/Sources/Generated/DriverPins.hpp (driver,
# C++) and Driver/Sources/Generated/DriverPins.h (C: tools/feedprobe) from scripts/lib/versions.sh
# (§7.2). --check exits 1 when a committed file is out of date; both exit 2 when versions.sh holds
# a value that cannot be generated (a selector that is not four printable ASCII characters).
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
# shellcheck source=lib/common.sh
. "$here/lib/common.sh"
# shellcheck source=lib/versions.sh
. "$here/lib/versions.sh"
root="$(cd "$here/.." && pwd)"
out="$root/Sources/TalkTalkCore/Generated/EnginePins.swift"

swift_list() { local x first=1; printf '['; for x in $1; do [ $first = 1 ] || printf ', '; printf '"%s"' "$x"; first=0; done; printf ']'; }

gen() {
  cat <<EOF
// Generated by scripts/gen-pins.sh from scripts/lib/versions.sh. Do not edit.
// check.sh fails when this file and versions.sh disagree.

public enum EnginePins {
    public static let appVersion = "$TT_APP_VERSION"
    public static let appBuild = "$TT_APP_BUILD"
    public static let engineAPI = $TT_ENGINE_API
    public static let engineRecipe = $TT_ENGINE_RECIPE
    public static let pythonVersion = "$TT_PY_VERSION"
    public static let pythonRelease = "$TT_PY_RELEASE"
    public static let mlxAudioCommit = "$TT_MLX_AUDIO_COMMIT"
    public static let lockSHA256 = "$TT_LOCK_SHA256"
    public static let lockCompat: [String] = $(swift_list "$TT_LOCK_COMPAT")
    public static let runtimeFlavours: [String] = $(swift_list "$TT_RUNTIME_FLAVOURS")

    public struct Model: Sendable, Equatable {
        public let key: String
        public let repo: String
        public let revision: String
        public let compatRevisions: [String]
        public let role: String
        public let license: String
        public let bytes: Int64
        public let fileCount: Int
        /// Every pinned file with its byte count: the app's start-up check stats these (§7.5 item 2);
        /// sha256 stays in versions.sh and is checked only by install-engine.sh --check.
        public let files: [File]
        public var directoryName: String { "\(repo.split(separator: "/").last!)@\(revision.prefix(12))" }
    }

    public struct File: Sendable, Equatable {
        public let path: String
        public let bytes: Int64
    }

    public static let models: [Model] = [
EOF
  local k
  for k in $TT_MODELS; do
    printf '        Model(key: "%s", repo: "%s", revision: "%s", compatRevisions: %s, role: "%s", license: "%s", bytes: %s, fileCount: %s, files: [\n' \
      "$k" "$(tt_model_field "$k" REPO)" "$(tt_model_field "$k" REVISION)" "$(swift_list "$(tt_model_field "$k" COMPAT_REVISIONS)")" \
      "$(tt_model_field "$k" ROLE)" "$(tt_model_field "$k" LICENSE)" "$(tt_model_bytes "$k")" \
      "$(tt_model_files "$k" | /usr/bin/wc -l | /usr/bin/tr -d ' ')"
    tt_model_files "$k" | /usr/bin/awk '{ printf "            File(path: \"%s\", bytes: %s),\n", $1, $2 }'
    printf '        ]),\n'
  done
  cat <<EOF
    ]

    public static let profiles: [String: [String]] = [
        "max": $(swift_list "$TT_PROFILE_MAX"),
        "standard": $(swift_list "$TT_PROFILE_STANDARD"),
        "compact24": $(swift_list "$TT_PROFILE_COMPACT24"),
        "compact16": $(swift_list "$TT_PROFILE_COMPACT16"),
    ]
}
EOF
}

# "ttmm" -> 0x74746D6D (bash 3.2: printf "'c" gives the character code). Called at the top level
# below, not inside the heredocs: a failing $(...) inside a heredoc does not stop the script.
# exit 2: versions.sh holds a value that cannot be generated (exit 1 stays "--check: out of date").
pins_die() { tt_log "error: $*"; exit 2; }
fourcc_hex() {
  local s="$1" i c h=""
  [ ${#s} -eq 4 ] || pins_die "gen-pins: selector \"$s\" is not four characters"
  for i in 0 1 2 3; do
    c="$(LC_ALL=C printf '%d' "'${s:$i:1}")"
    { [ "$c" -ge 32 ] && [ "$c" -le 126 ]; } || pins_die "gen-pins: selector \"$s\" is not printable ASCII"
    h="$h$(printf '%02X' "$c")"
  done
  printf '0x%s' "$h"
}
# set -e stops the script here (exit 2 from pins_die) before anything is written or compared.
diag_sel_hex="$(fourcc_hex "$TT_DRIVER_DIAG_SELECTOR")"
mm_sel_hex="$(fourcc_hex "$TT_DRIVER_MEETING_MODE_SELECTOR")"

gen_driver_swift() {
  cat <<EOF
// Generated by scripts/gen-pins.sh from scripts/lib/versions.sh. Do not edit.
// check.sh fails when this file and versions.sh disagree. The driver reads the same values
// from Driver/Sources/Generated/DriverPins.hpp.

public enum DriverPins {
    public static let version = "$TT_DRIVER_VERSION"
    public static let bundleID = "$TT_DRIVER_BUNDLE_ID"
    public static let bundleName = "$TT_DRIVER_BUNDLE_NAME"
    public static let feedUID = "$TT_DRIVER_FEED_UID"
    public static let micUID = "$TT_DRIVER_MIC_UID"
    public static let testMicUID = "$TT_DRIVER_TESTMIC_UID"
    /// Every UID talktalk creates is this or starts with this + "." (Feed, Mic, Test Mic, taps).
    public static let ownUIDPrefix = "$TT_DRIVER_OWN_UID_PREFIX"
    /// Private tap aggregates created by MeetingTap.
    public static let tapUIDPrefix = "$TT_DRIVER_TAP_UID_PREFIX"
    /// Custom properties on TalkTalk Feed: 'ttdg' diagnostics (CFDictionary, read-only) and
    /// 'ttmm' meeting-mode switch (CFNumber 0/1, only accepted Feed clients may write it).
    public static let diagnosticsSelector: UInt32 = $diag_sel_hex   // '$TT_DRIVER_DIAG_SELECTOR'
    public static let meetingModeSelector: UInt32 = $mm_sel_hex   // '$TT_DRIVER_MEETING_MODE_SELECTOR'
    public static let libASPLVersion = "$TT_LIBASPL_VERSION"
    public static let libASPLCommit = "$TT_LIBASPL_COMMIT"
}
EOF
}

gen_driver_hpp() {
  cat <<EOF
// Generated by scripts/gen-pins.sh from scripts/lib/versions.sh. Do not edit.
// check.sh fails when this file and versions.sh disagree. Swift reads the same values from
// Sources/TalkTalkCore/Generated/DriverPins.swift.

#pragma once

namespace tt::pins {

constexpr const char* kDriverVersion = "$TT_DRIVER_VERSION";
constexpr const char* kDriverBundleID = "$TT_DRIVER_BUNDLE_ID";
constexpr const char* kModelUID = "$TT_DRIVER_BUNDLE_ID.model";
constexpr const char* kFeedUID = "$TT_DRIVER_FEED_UID";
constexpr const char* kMicUID = "$TT_DRIVER_MIC_UID";
constexpr const char* kTestMicUID = "$TT_DRIVER_TESTMIC_UID";
constexpr const char* kOwnUIDPrefix = "$TT_DRIVER_OWN_UID_PREFIX";
constexpr const char* kTapUIDPrefix = "$TT_DRIVER_TAP_UID_PREFIX";
constexpr unsigned int kDiagnosticsSelector = ${diag_sel_hex}u; // '$TT_DRIVER_DIAG_SELECTOR'
constexpr unsigned int kMeetingModeSelector = ${mm_sel_hex}u; // '$TT_DRIVER_MEETING_MODE_SELECTOR'

} // namespace tt::pins
EOF
}

gen_driver_h() {
  cat <<EOF
/* Generated by scripts/gen-pins.sh from scripts/lib/versions.sh. Do not edit.
 * check.sh fails when this file and versions.sh disagree. For C code (tools/feedprobe); the driver
 * reads the same values from DriverPins.hpp, Swift from Sources/TalkTalkCore/Generated/DriverPins.swift. */

#pragma once

#define TT_PINS_FEED_UID "$TT_DRIVER_FEED_UID"
#define TT_PINS_DIAGNOSTICS_SELECTOR ${diag_sel_hex}u /* '$TT_DRIVER_DIAG_SELECTOR' */
#define TT_PINS_MEETING_MODE_SELECTOR ${mm_sel_hex}u /* '$TT_DRIVER_MEETING_MODE_SELECTOR' */
EOF
}

driver_swift="$root/Sources/TalkTalkCore/Generated/DriverPins.swift"
driver_hpp="$root/Driver/Sources/Generated/DriverPins.hpp"
driver_h="$root/Driver/Sources/Generated/DriverPins.h"
targets="gen:$out gen_driver_swift:$driver_swift gen_driver_hpp:$driver_hpp gen_driver_h:$driver_h"

if [ "${1:-}" = "--check" ]; then
  bad=0
  for t in $targets; do
    f="${t#*:}"
    if "${t%%:*}" | /usr/bin/cmp -s - "$f"; then tt_log "$(/usr/bin/basename "$f"): in sync"
    else tt_log "$(/usr/bin/basename "$f") is out of date; run scripts/gen-pins.sh"; bad=1; fi
  done
  exit $bad
fi
for t in $targets; do
  f="${t#*:}"
  /bin/mkdir -p "$(/usr/bin/dirname "$f")"
  "${t%%:*}" > "$f"
  tt_log "wrote $f"
done
