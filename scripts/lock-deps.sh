#!/bin/bash
# lock-deps.sh: regenerate engine/requirements-engine.lock and engine/requirements-build.lock.
#
# uv resolves every dependency with hashes. mlx-audio is pinned to a GitHub commit tarball, which
# uv refuses to unpack (a file name in examples/ contains ':'), so resolution goes through the PyPI
# release whose pyproject dependencies are identical (checked below), and the tarball line is added
# afterwards with its sha256. pip installs that line with --require-hashes like any other.
# sounddevice is left out on purpose: the engine stubs it (no PortAudio, no Core Audio client).
# Network: pypi.org, files.pythonhosted.org, github.com.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
# shellcheck source=lib/common.sh
. "$here/lib/common.sh"
root="$(cd "$here/.." && pwd)"
eng="$root/engine"

MLX_AUDIO_COMMIT="f65753b55f011f4cc8b1dbc7622ae8110b7b7fbb"
MLX_AUDIO_PROXY="mlx-audio==0.6.4"   # same [project.dependencies] as the commit above
MLX_AUDIO_URL="https://github.com/Neywa-Labs/mlx-audio/archive/$MLX_AUDIO_COMMIT.tar.gz"

command -v uv >/dev/null || tt_die "uv not found (brew install uv)"
export MACOSX_DEPLOYMENT_TARGET=26.0   # mlx 0.32.4 ships macosx_14/15/26 wheels only
export UV_CACHE_DIR="${UV_CACHE_DIR:-${TMPDIR:-/tmp}/tt-uv-cache}"
tmp="$(/usr/bin/mktemp -d "${TMPDIR:-/tmp}/tt-lock.XXXXXX")"
trap '/bin/rm -rf "$tmp"' EXIT

# 1. Fetch the tarball and hash it; confirm its dependency list matches the proxy release.
/usr/bin/curl -fsSL --proto '=https' --retry 3 -o "$tmp/mlx-audio.tar.gz" "$MLX_AUDIO_URL"
url_sha="$(tt_sha256 "$tmp/mlx-audio.tar.gz")"
/usr/bin/tar -xzf "$tmp/mlx-audio.tar.gz" -C "$tmp" "mlx-audio-$MLX_AUDIO_COMMIT/pyproject.toml"
/usr/bin/awk '/^dependencies = \[/{f=1;next} f&&/^\]/{f=0} f' "$tmp/mlx-audio-$MLX_AUDIO_COMMIT/pyproject.toml" \
  | /usr/bin/tr -d ' ",' | /usr/bin/sed '/^$/d' | LC_ALL=C /usr/bin/sort > "$tmp/deps.commit"
/usr/bin/curl -fsSL --proto '=https' --retry 3 "https://pypi.org/pypi/${MLX_AUDIO_PROXY%%==*}/${MLX_AUDIO_PROXY##*==}/json" \
  | /usr/bin/jq -r '.info.requires_dist[] | select(test("extra ==") | not)' \
  | /usr/bin/tr -d ' ' | LC_ALL=C /usr/bin/sort > "$tmp/deps.proxy"
if ! /usr/bin/diff -u "$tmp/deps.commit" "$tmp/deps.proxy" >&2; then
  tt_die "mlx-audio dependencies at $MLX_AUDIO_COMMIT differ from $MLX_AUDIO_PROXY; update the proxy"
fi

# 2. Resolve with the proxy, then swap in the pinned tarball.
/usr/bin/sed "s|^mlx-audio @ .*|$MLX_AUDIO_PROXY|" "$eng/requirements-engine.in" > "$tmp/engine.in"
uv pip compile "$tmp/engine.in" -o "$tmp/engine.lock" --generate-hashes --no-header --quiet \
  --python-version 3.12 --python-platform aarch64-apple-darwin \
  --no-emit-package sounddevice --no-emit-package mlx-audio
{
  printf '# Generated by scripts/lock-deps.sh from engine/requirements-engine.in. Do not edit.\n'
  printf '# Install: pip install --require-hashes --no-deps --no-build-isolation -r requirements-engine.lock\n'
  printf '# (after requirements-build.lock). sounddevice is intentionally absent (engine stub).\n'
  /bin/cat "$tmp/engine.lock"
  printf 'mlx-audio @ %s \\\n    --hash=sha256:%s\n    # via -r requirements-engine.in (commit tarball; resolved as %s)\n' \
    "$MLX_AUDIO_URL" "$url_sha" "$MLX_AUDIO_PROXY"
} > "$eng/requirements-engine.lock"

uv pip compile "$eng/requirements-build.in" -o "$tmp/build.lock" --generate-hashes --no-header --quiet \
  --python-version 3.12 --python-platform aarch64-apple-darwin
{
  printf '# Generated by scripts/lock-deps.sh from engine/requirements-build.in. Do not edit.\n'
  /bin/cat "$tmp/build.lock"
} > "$eng/requirements-build.lock"

tt_log "requirements-engine.lock sha256 $(tt_sha256 "$eng/requirements-engine.lock")"
tt_log "requirements-build.lock  sha256 $(tt_sha256 "$eng/requirements-build.lock")"
tt_log "mlx-audio tarball sha256 $url_sha"
tt_log "update TT_LOCK_SHA256 / TT_BUILD_LOCK_SHA256 in scripts/lib/versions.sh"
